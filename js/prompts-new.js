// 回覆中的 LaTeX 數學式轉成純文字（例如 $\\beta = -0.163, p = 0.013$ → β = −0.163, p = 0.013）
const TEX = { alpha: "α", beta: "β", gamma: "γ", delta: "δ", Delta: "Δ", epsilon: "ε", eta: "η", theta: "θ", lambda: "λ", mu: "μ", rho: "ρ", sigma: "σ", Sigma: "Σ", tau: "τ", phi: "φ", chi: "χ", omega: "ω",
  times: "×", cdot: "·", pm: "±", leq: "≤", le: "≤", geq: "≥", ge: "≥", neq: "≠", approx: "≈", rightarrow: "→", to: "→", leftarrow: "←", infty: "∞", sim: "~", ldots: "…", dots: "…", circ: "°" };
function deLatex(text) {
  const conv = m => m
    .replace(/\\(?:text|mathrm|mathit|mathbf|textit|textbf|operatorname)\{([^{}]*)\}/g, "$1")
    .replace(/\\([A-Za-z]+)/g, (x, n) => TEX[n] ?? x)
    .replace(/\^\{?2\}?/g, "²").replace(/\^\{?3\}?/g, "³").replace(/_\{([^{}]*)\}/g, "$1")
    .replace(/\\[,;! ]/g, " ").replace(/[{}]/g, "")
    .replace(/(^|[\s(=,])-(?=\d|\.)/g, "$1−").replace(/\s+/g, " ").trim();
  return String(text || "").replace(/\$\$([\s\S]+?)\$\$/g, (_, m) => conv(m)).replace(/\$([^$\n]+?)\$/g, (_, m) => conv(m))
    .replace(/\\\(([\s\S]+?)\\\)/g, (_, m) => conv(m));
}

// 問卷草稿：解析「## 問卷草稿」一節 → { intro, screen, manip, scale, constructs:[{ name, src, dim, items:[{ id, zh, en }], missing }], demo }
// 選項：去掉 AI 自行加上的 ○ □ 等符號；題目或選項含「複選」或方框者視為複選題
const svOpts = t => String(t || "").split(/[／/]/).map(x => x.replace(/^[\s○◯●◎□☐■◻▢☑✓]+/, "").trim()).filter(Boolean);
const svMulti = (q, t) => /複選|多選/.test(q || "") || /^[\s]*[□☐■◻▢☑]/.test(t || "");
function parseSurvey(text) {
  const t = String(text || "").replace(/\r\n?/g, "\n").replace(/\*\*/g, "");
  const m = lastSection(t, /^#{1,3}\s*問卷草稿[^\n]*\n([\s\S]*?)(?=^#{1,2}\s(?!#)|(?![\s\S]))/gm);
  if (!m) return null;
  const S = { intro: "", screen: [], manip: [], scaleText: "", constructs: [], demo: [], other: [] };
  const row = l => l.replace(/^[-*•]\s*/, "").split(/\s*[｜|]\s*/);
  let last = "start";   // 其他部分（例如情境回想）依出現位置排在前一個部分之後
  m[1].split(/^(?=#{3,4}\s)/m).filter(b => /^#{3,4}\s/.test(b)).forEach(b => {
    const lines = b.split("\n"), head = lines[0].replace(/^#+\s*/, "").replace(/（[^）]*每行一題[^）]*）$/, "").trim(), body = lines.slice(1).map(x => x.trim()).filter(Boolean);
    const kind = /^填答說明/.test(head) ? "intro" : /^篩選題/.test(head) ? "screen" : /^基本資料/.test(head) ? "demo" : /^量尺/.test(head) ? "scale"
      : /^(操弄|注意力)/.test(head) ? "manip" : /^構念/.test(head) || head.split(/[｜|]/).length >= 3 ? "con" : "other";
    if (kind === "other") {
      const qs = [], text = [];
      body.forEach(l => { const r = row(l); if (r.length >= 2 && /^[A-Za-z]{1,3}\d+$/.test(r[0])) qs.push({ id: r[0].toUpperCase(), q: r[1], opts: svOpts(r[2]), multi: svMulti(r[1], r[2]) }); else text.push(l.replace(/^[-*•]\s*/, "")); });
      S.other.push({ head, text: text.join("\n"), qs, after: last });
      return;
    }
    last = kind === "con" ? "con" + S.constructs.length : kind;   // 構念：記下是第幾個構念之後（push 前的長度＝本構念的索引）
    if (/^填答說明/.test(head)) S.intro = body.join("\n");
    else if (/^篩選題/.test(head)) S.screen = body.map(row).filter(c => c.length >= 2).map(c => ({ id: c[0], q: c[1], opts: svOpts(c[2]), multi: svMulti(c[1], c[2]) }));
    else if (kind === "manip") S.manip = body.map(row).filter(c => c.length >= 2).map(c => ({ id: c[0], q: c[1], opts: [] }));
    else if (/^基本資料/.test(head)) S.demo = body.map(row).filter(c => c.length >= 2).map(c => ({ id: c[0], q: c[1], opts: svOpts(c[2]), multi: svMulti(c[1], c[2]) }));
    else if (/^量尺/.test(head)) S.scaleText = body.join(" ");
    else if (/^構念/.test(head) || head.split(/[｜|]/).length >= 3) {
      const c = head.replace(/^構念\s*[｜|]\s*/, "").split(/\s*[｜|]\s*/);
      const con = { name: c[0], src: c[1] || "", dim: c[2] || "", stem: "", items: [], missing: "" };
      body.forEach(l => {
        if (/待補量表/.test(l)) { con.missing = l; return; }
        const st = l.match(/^[-*•]?\s*(?:共同)?題幹\s*[：:]\s*(.+)$/); if (st) { con.stem = st[1].trim(); return; }
        const r = row(l); if (r.length >= 2 && /^Q?\d+/i.test(r[0])) con.items.push({ id: r[0].toUpperCase().replace(/^(\d)/, "Q$1"), zh: r[1], en: r[2] || "" });
      });
      S.constructs.push(con);
    } else S.other.push({ head, text: body.join("\n"), qs: [], after: last });
  });
  const nums = [...S.scaleText.matchAll(/(\d+)\s*[＝=]/g)].map(x => +x[1]);
  S.points = nums.length ? Math.max(...nums) : /五點/.test(S.scaleText) ? 5 : 7;
  S.ends = (() => { const a = S.scaleText.match(/1\s*[＝=]\s*([^／/、,，；;（(]+)/), z = S.scaleText.match(new RegExp(S.points + "\\s*[＝=]\\s*([^／/、,，；;（(]+)")); return [a ? a[1].trim() : "", z ? z[1].trim() : ""]; })();
  return S;
}

