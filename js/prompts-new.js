function buildMatrix(on) {
  const cols = MATRIX_COLS.filter(c => c.locked || on.includes(c.key));
  const has = k => cols.some(c => c.key === k);
  const rules = [
    "每一篇文獻各佔一列，不得將兩篇文獻合併在同一列。",
    "依發表年份由新到舊排列。",
    "所有內容只依據該篇文獻原文，不得推測或補充原文以外的資訊。",
    "原文未提及的欄位，一律填「未提及」；只有摘要的文獻，在「文獻」欄加註「僅有摘要」。",
    "變數與理論名稱以原文英文為主，並在括號中附上中文翻譯，例如：Perceived Value（知覺價值）。",
    "一個欄位有多個變數或量表時，以分號分隔。"
  ];
  const pairs = [];
  if (has("purpose") && has("gap")) pairs.push("研究目的須對應研究缺口");
  if (has("conclusion") && has("purpose")) pairs.push("研究結論須對應研究目的");
  if (pairs.length) rules.push(`${pairs.join("，")}；若原文中兩者無法對應，請在該欄加註「待確認」。`);
  rules.push(has("method")
    ? "每個欄位以一至兩句精簡描述；「量表與研究方法」欄可稍長，但以三句為限。使用繁體中文。"
    : "每個欄位以一至兩句精簡描述。使用繁體中文。");
  return [
    "請將筆記本中的每一篇文獻整理為表格的一列，欄位依序如下：",
    ...cols.map((c, i) => `${i + 1}. ${c.label}${c.desc ? "：" + c.desc : ""}`),
    "",
    "填寫規則：",
    ...rules.map(r => "- " + r)
  ].join("\n");
}

