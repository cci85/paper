T.discuss = p => {
  const secs = Object.keys(DISCUSS_SECS).filter(k => p.secs.includes(k));
  return [
    "以下是本研究的假說檢定結果：",
    "", "---", p.results, "---", "",
    `研究情境與樣本：${blank(p.ctx) ? "未提供" : p.ctx}`,
    "",
    "任務：僅根據此 Notebook 中上傳的文獻與上方的檢定結果，撰寫論文第五章的下列各節。",
    "",
    ...secs.flatMap(k => [`## ${DISCUSS_SECS[k][0]}`, DISCUSS_SECS[k][1], ""]),
    "共同規則：",
    "1. 檢定結果的數值與支持與否，只能依上方提供的內容，不得更改或補充。",
    "2. 對照文獻時，只能引用上傳文獻中確實檢驗過相同或相近關係的研究；找不到可對照的文獻時，標示「上傳文獻中無可對照之研究」，不得憑常識寫成「與過去研究一致」。",
    "3. 解釋不一致結果的原因時，只能提出有文獻依據的可能解釋，並以「可能」陳述，不得寫成已證實的結論。",
    "4. 以連貫的段落撰寫，不使用條列；用詞一律使用「變數」，不得使用「變項」。"
  ].join("\n");
};

// 研究方向聚焦：有填欄位時，以已提供的資訊取代第零節
function buildFocus(p) {
  const filled = ["f_phen", "f_dir", "f_res", "f_prev"].some(k => !blank(p[k]));
  if (!filled) return [T.focus_head, "", T.focus_zero, "", T.focus_body, "", T.focus_start].join("\n");
  const val = k => blank(p[k]) ? "無" : p[k].trim();
  const zero = [
    "零、我已提供的資訊",
    "以下是我事先填寫的內容，標示「無」者代表沒有：",
    `- 感興趣的現象或研究方向：${val("f_phen")}`,
    `- 想要的研究方向：${val("f_dir")}`,
    `- 可運用的資源：${val("f_res")}`,
    `- 前次的研究問題草稿與檢索字串：${val("f_prev")}`
  ].join("\n");
  const start = !blank(p.f_prev)
    ? "請依我提供的前次研究問題草稿與檢索字串，直接從第三節開始。"
    : !blank(p.f_phen)
      ? "請依第一節第 4 點回覆後，從第二節的第一題開始。"
      : "請先只問我一個問題：「請描述你感興趣的現象或研究方向。」並附上 2–3 個口語描述的例子；我回答後，依第一節第 4 點回覆，再從第二節的第一題開始。";
  return [T.focus_head, "", zero, "", T.focus_body, "", start].join("\n");
}
