// 研究方向聚焦：有填欄位時，以已提供的資訊取代第零節
function buildFocus(p) {
  const filled = ["f_phen", "f_dir", "f_res", "f_prev"].some(k => !blank(p[k]));
  if (!filled) return [T.focus_head, "", T.focus_zero, "", T.focus_body, "", T.focus_start].join("\n");
  const val = k => blank(p[k]) ? "無" : p[k].trim();
  const zero = [
    "零、我已提供的資訊",
    "以下是我事先填寫的內容，標示「無」者代表沒有：",
    `- 感興趣的現象或研究方向：${val("f_phen")}`,
    `- 想要的研究方向：${val("f_dir")}`,
    `- 可運用的資源：${val("f_res")}`,
    `- 前次的研究問題草稿與檢索字串：${val("f_prev")}`
  ].join("\n");
  const start = !blank(p.f_prev)
    ? "請依我提供的前次研究問題草稿與檢索字串，直接從第三節開始。"
    : !blank(p.f_phen)
      ? "請依第一節第 4 點回覆後，從第二節的第一題開始。"
      : "請先只問我一個問題：「請描述你感興趣的現象或研究方向。」並附上 2–3 個口語描述的例子；我回答後，依第一節第 4 點回覆，再從第二節的第一題開始。";
  return [T.focus_head, "", zero, "", T.focus_body, "", start].join("\n");
}

