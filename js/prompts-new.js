const MIX_ROLES = [["iv", "自變數"], ["med", "中介變數"], ["mod", "調節變數"], ["dv", "依變數"]];
function parseVarList(text) {
  if (blank(text)) return [];
  const i = text.search(/變數清單/);
  const body = i >= 0 ? text.slice(i) : text;
  const seen = new Set(), out = [];
  body.split(/\r?\n/).forEach(line => {
    const cells = line.replace(/^[\s>*•\-–]+|^\d+[.、)]\s*/g, "").split(/\s*[｜|\t]\s*/).map(c => c.trim()).filter(Boolean);
    if (cells.length < 2 || /^-+$/.test(cells[0])) return;
    const r = cells[0];
    const role = /自變/.test(r) ? "iv" : /中介/.test(r) ? "med" : /調節|干擾/.test(r) ? "mod" : /依變|應變|結果變/.test(r) ? "dv" : "";
    if (!role) return;
    const name = cells[1], key = role + "｜" + name;
    if (seen.has(key)) return;
    seen.add(key);
    out.push({ key, role, name, src: cells[2] || "", frames: cells[3] || "", extra: /未納入/.test(cells[3] || "") });
  });
  return out;
}
